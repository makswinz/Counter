    /// <summary>Resolves what a theme preference actually means right now.</summary>
    public static IReadOnlyDictionary<string, string> For(
        ThemePreference preference,
        bool systemIsLight,
        AccentPalette accent,
        GlassMaterial material = GlassMaterials.Default) =>
        Solids(IsLight(preference, systemIsLight), accent, material);

    public static bool IsLight(ThemePreference preference, bool systemIsLight) => preference switch
    {
        ThemePreference.Light => true,
        ThemePreference.Dark => false,
        _ => systemIsLight
    };

    public static string Label(ThemePreference preference) => preference switch
    {
        ThemePreference.Light => "Light",
        ThemePreference.Dark => "Dark",
        _ => "System"
    };

    public static ThemePreference Parse(string? value) => value?.Trim().ToLowerInvariant() switch
    {
        "light" => ThemePreference.Light,
        "dark" => ThemePreference.Dark,
        _ => ThemePreference.System
    };
}
