    /// <summary>
    /// What each glass is made of, as the difference from the theme's own neutral set.
    ///
    /// Only the keys that actually change are listed. Writing complete dictionaries per material
    /// would mean several places to forget an ink colour, and the whole point of the neutral set
    /// is that it is one place.
    ///
    /// <para>
    /// The density depends on whether there is a real blur behind the panel, and it has to. A
    /// frosted card on a web page can sit at eighteen percent because <c>backdrop-filter</c> has
    /// already destroyed the detail behind it before the tint arrives; the tint is only tinting a
    /// wash. Take the blur away and the same alpha leaves a browser with readable text in it
    /// sitting under the timer. So there are two tables: one for a panel with acrylic underneath
    /// it, which is close to the reference, and one for a panel with the bare desktop underneath,
    /// which is as thin as legibility allows and no thinner.
    /// </para>
    /// </summary>
    public static IReadOnlyDictionary<string, string> GlassOverrides(
        bool isLight, GlassMaterial material, bool blurred = false)
    {
        if (material == GlassMaterial.Solid)
        {
            return new Dictionary<string, string>();
        }

        var frosted = material == GlassMaterial.Frosted;

        // body, raised, deep, hover: the four glass densities, in the order the surfaces stack.
        var alphas = (frosted, blurred, isLight) switch
        {
            // Frosted over acrylic. Thinner than it is without one, because the acrylic is
            // already carrying a tint of its own - but not as thin as the reference designs,
            // and for a measured reason. A blur destroys detail; it does not change luminance.
            // A white wallpaper blurred is still white, and text on a surface that is mostly
            // white wallpaper is text nobody can read.
            (true, true, true) => new byte[] { 0x73, 0x80, 0x80, 0x92 },
            (true, true, false) => new byte[] { 0x86, 0x93, 0x93, 0xA4 },

            // Frosted over the bare desktop. Denser than it would like to be, because with
            // nothing blurring behind it the tint is the only thing standing between the user
            // and their own browser, and a panel you can read through is not frosted glass, it
            // is a window.
            (true, false, true) => new byte[] { 0xD4, 0xDE, 0xDE, 0xE6 },
            (true, false, false) => new byte[] { 0xCE, 0xD8, 0xD8, 0xDA },

            // Liquid over acrylic: the thinnest sheet in the application, and the one that
            // had to give the most ground. It is still the material you can see the most
            // through, which is the idea of it; it is no longer one you can read a browser
            // through, which was never the idea of it.
            (false, true, true) => new byte[] { 0x42, 0x4E, 0x4E, 0x60 },
            (false, true, false) => new byte[] { 0x40, 0x4C, 0x4C, 0x5C },

            // Liquid over the bare desktop. Still the thinnest of the three, but the gap
            // between it and frosted is now carried by the edge rather than by transparency.
            (false, false, true) => new byte[] { 0xC2, 0xCE, 0xCE, 0xD8 },
            _ => new byte[] { 0xBC, 0xC8, 0xC8, 0xD2 }
        };

        var body = isLight
            ? new[] { "FFFFFF", "FFFFFF", "F5F8FC", "FFFFFF" }
            : new[] { "16191F", "1A1E26", "0E1116", "232935" };

        string Glass(int index) =>
            "#" + alphas[index].ToString("X2", CultureInfo.InvariantCulture) + body[index];

        var map = new Dictionary<string, string>
        {
            ["GlassBaseBrush"] = Glass(0),
            ["GlassRaisedBrush"] = Glass(1),
            ["GlassDeepBrush"] = Glass(2),
            ["GlassHoverBrush"] = Glass(3),

            // A pale wash over the body rather than instead of it: the reference's near-white
            // fill is the whole surface on a light page, and here it is the part of the surface
            // that catches the light. Liquid glass tints nothing at all, exactly as written.
            // The pale wash frosted glass carries. Lighter in the dark theme than the
            // reference asks for, because a white wash on a dark panel is the one layer that
            // works directly against the ink standing on it: every point of it is a point of
            // contrast taken from text that had none to spare.
            ["GlassTintBrush"] = frosted
                ? (isLight ? "#2EFAFAFA" : "#12FAFAFA")
                : "#00FFFFFF",

            ["RowGlassBrush"] = isLight ? (frosted ? "#5CFFFFFF" : "#4AFFFFFF") : (frosted ? "#12FFFFFF" : "#0EFFFFFF"),
            ["RowGlassHoverBrush"] = isLight ? (frosted ? "#94FFFFFF" : "#80FFFFFF") : (frosted ? "#24FFFFFF" : "#1FFFFFFF"),

            // Frosted: the reference's inset 0 0 4px 2px rgba(255,255,255,0.45).
            // Liquid: its inset 0 0 12px -4px at 0.7, and the outward 0 0 21px -8px at 0.3.
            ["GlassRimBrush"] = frosted ? "#73FFFFFF" : "#B3FFFFFF",
            ["GlassHaloBrush"] = frosted ? "#00FFFFFF" : "#4DFFFFFF"
        };

        foreach (var (key, value) in Ink(material, isLight))
        {
            map[key] = value;
        }

        return map;
    }

    /// <summary>
    /// The quiet end of the ink ladder, per material.
    ///
    /// Quieter ink over a translucent panel is not quiet, it is gone. The contrast a muted tone
    /// was measured against was a solid surface, and there is no solid surface here: the panel
    /// shows whatever is behind it, and what is behind it is a wallpaper nobody chose for its
    /// legibility. So each step moves back toward the primary ink by roughly what the surface
    /// gives away, and the thinner the material the further it moves.
    ///
    /// The numbers are not taste. They come from photographing the real window over a field of
    /// saturated bands - pure white and pure black among them - measuring the worst surface
    /// luminance each material actually produces, and solving for the ink that clears 4.5:1 for
    /// text and 3:1 for the muted tone at that luminance. See docs/DESIGN.md.
    /// </summary>
    private static Dictionary<string, string> Ink(GlassMaterial material, bool isLight)
    {
        var ink = (material, isLight) switch
        {
            // Frosted: a pale wash over the blur, which costs the dark theme more than the
            // light one because the wash and the ink are pulling the same direction there.
            (GlassMaterial.Frosted, true) => new[] { "#FF44505F", "#FF6B7788", "#FF9AA5B2" },
            (GlassMaterial.Frosted, false) => new[] { "#FFD2DAE6", "#FFADB7C5", "#FF7B8694" },

            // Liquid: the thinnest, so the ladder is the most compressed.
            (_, true) => new[] { "#FF35404E", "#FF57626F", "#FF8B96A3" },
            _ => new[] { "#FFDEE5EC", "#FFB2BCC9", "#FF868F9C" }
        };

        return new Dictionary<string, string>
        {
            ["TextSecondaryBrush"] = ink[0],
            ["TextMutedBrush"] = ink[1],
            ["TextDisabledBrush"] = ink[2]
        };
    }

    // ==================================================================== assembly

    /// <summary>Every solid colour for one theme, one accent and one glass, keyed by resource name.</summary>
    public static IReadOnlyDictionary<string, string> Solids(
        bool isLight,
        AccentPalette accent,
        GlassMaterial material = GlassMaterials.Default,
        bool blurred = false)
    {
        var map = new Dictionary<string, string>(isLight ? Light : Dark);

        foreach (var (key, value) in GlassOverrides(isLight, material, blurred))
        {
            map[key] = value;
        }

        foreach (var (key, value) in AccentColours(accent, isLight))
        {
            map[key] = value;
        }

        foreach (var (key, value) in SemanticColours(isLight))
        {
            map[key] = value;
        }

        return map;
    }

    /// <summary>Every gradient, keyed by resource name. All five-stop, all one family each.</summary>
    public static IReadOnlyDictionary<string, GradientRamp> Gradients(AccentPalette accent)
    {
        var ramp = Ramp(accent);

        return new Dictionary<string, GradientRamp>
        {
            // Ongoing work wears the colour the user chose. Three keys rather than one, because
            // the fill, the contour and the running state are separable ideas even when they
            // happen to resolve to the same ramp.
            ["AccentGradientBrush"] = ramp,
            ["AccentContourBrush"] = ramp,
            ["RunningGradientBrush"] = ramp,

            // The state ramps do not, so a held timer stays amber and a failure stays red
            // whatever colour the user likes.
            ["PausedGradientBrush"] = Paused,
            ["WarningGradientBrush"] = Warning,
            ["DangerGradientBrush"] = Danger,
            ["SuccessGradientBrush"] = Success
        };
    }

    /// <summary>The five stops of the chosen accent, in gradient order.</summary>
    public static GradientRamp Ramp(AccentPalette accent) => GradientRamp.From(accent.Ramp);

    // ==================================================================== accent

    /// <summary>
    /// Everything the accent drives, derived rather than listed.
    ///
    /// The seven ramp stops come straight from the engine. The rest is arithmetic on them: a
    /// hover tone is the ink moved a third of the way toward the lit stop, a pressed tone a third
    /// toward the shadowed one, and the heat ramp is the ink mixed into the empty-cell surface in
    /// four even steps. Written out by hand, six palettes times two themes would be several
    /// hundred values to keep in step, and a custom colour could not exist at all.
    /// </summary>
    private static Dictionary<string, string> AccentColours(AccentPalette accent, bool isLight)
    {
        var ramp = accent.Ramp;

        var highlight = ToColor(ramp.Highlight);
        var light = ToColor(ramp.Light);
        var mid = ToColor(ramp.Base);
        var strong = ToColor(ramp.Strong);
        var deep = ToColor(ramp.Deep);
        var shadow = ToColor(ramp.Shadow);
        var glow = ToColor(ramp.Glow);

        // Which end of the ramp reads as "the accent" depends on what it is drawn against. On a
        // dark surface the base is the right weight; on white it is too pale to be legible as
        // text or as a hairline, so the light theme takes the strong stop.
        var ink = isLight ? strong : mid;
        var surface = ToColor(isLight ? Light["HeatBrush0"] : Dark["HeatBrush0"]);

        return new Dictionary<string, string>
        {
            // The seven generated stops, for anything that builds its own thing from them.
            ["AccentHighlightBrush"] = Hex(highlight),
            ["AccentLightBrush"] = Hex(light),
            ["AccentBaseBrush"] = Hex(mid),
            ["AccentStrongBrush"] = Hex(strong),
            ["AccentDeepBrush"] = Hex(deep),
            ["AccentShadowBrush"] = Hex(shadow),
            ["AccentGlowBrush"] = Hex(glow),
            ["AccentForegroundBrush"] = ramp.Foreground,
            ["AccentGlyphBrush"] = ramp.Glyph,

            // Solid accent, for text, icons and hairlines.
            ["AccentBrush"] = Hex(ink),
            ["AccentHoverBrush"] = Hex(Mix(ink, light, 0.35)),
            ["AccentPressedBrush"] = Hex(Mix(ink, deep, 0.35)),

            // A wash behind a selected icon button, and the warm light the glass picks up close
            // to an active control. Low enough to read as a tint on the surface rather than as a
            // second control, and never applied behind an inactive row.
            ["AccentSoftBrush"] = Hex(WithAlpha(mid, isLight ? (byte)0x22 : (byte)0x2E)),
            ["AccentSoftTintBrush"] = Hex(WithAlpha(mid, isLight ? (byte)0x12 : (byte)0x16)),

            ["PrimaryFillBrush"] = Hex(ink),
            ["PrimaryFillHoverBrush"] = Hex(Mix(ink, light, 0.35)),
            ["PrimaryFillPressedBrush"] = Hex(Mix(ink, deep, 0.35)),
            ["SelectionFillBrush"] = Hex(ink),

            ["EdgeRunningBrush"] = Hex(ink),
            ["EdgeNotchRunningBrush"] = Hex(ink),
            ["ProgressRunningBrush"] = Hex(ink),

            ["FocusRingBrush"] = Hex(ink),
            ["RowFocusedBorderBrush"] = Hex(Mix(surface, ink, isLight ? 0.45 : 0.55)),
            ["NotchGlowBrush"] = Hex(glow),

            ["ChartBarBrush"] = Hex(ink),
            ["ChartBarManualBrush"] = Hex(Mix(surface, ink, 0.55)),

            // Four steps from the empty-cell surface to the accent. Evenly spaced so the ramp
            // reads as intensity rather than as four unrelated colours.
            ["HeatBrush1"] = Hex(Mix(surface, ink, 0.30)),
            ["HeatBrush2"] = Hex(Mix(surface, ink, 0.55)),
            ["HeatBrush3"] = Hex(Mix(surface, ink, 0.80)),
            ["HeatBrush4"] = Hex(ink),
            ["HeatTodayRingBrush"] = isLight ? Light["TextSecondaryBrush"] : "#FF8FA3BC"
        };
    }

    // ==================================================================== semantic

    private static Dictionary<string, string> SemanticColours(bool isLight)
    {
        // The strong stop on white, the base stop on a dark surface. Same family either way, so
        // the meaning of the colour never moves even though its tone does.
        string Tone(GradientRamp ramp) => isLight ? ramp.Strong : ramp.Base;

        var danger = ToColor(Tone(Danger));
        var success = ToColor(Tone(Success));

        return new Dictionary<string, string>
        {
            ["PausedBrush"] = Tone(Paused),
            ["WarningBrush"] = Tone(Warning),
            ["DangerBrush"] = Tone(Danger),
            ["SuccessBrush"] = Tone(Success),

            ["EdgePausedBrush"] = Tone(Paused),
            ["EdgeUrgentBrush"] = Tone(Danger),
            ["EdgeCompletedBrush"] = Tone(Success),

            ["ProgressPausedBrush"] = Tone(Paused),
            ["ProgressUrgentBrush"] = Tone(Danger),
            ["ProgressCompletedBrush"] = Tone(Success),

            // A finished task takes the completion family rather than the accent - the wash
            // behind the row, the control that was ticked, and the ink inside it. Completion is a
            // meaning, not a preference: it cannot follow the colour somebody chose, or a green
            // accent would make every open task look done. The checkmark and the struck-through
            // title carry it whether or not anybody can see the colour at all.
            ["SuccessSoftBrush"] = Hex(WithAlpha(success, isLight ? (byte)0x1A : (byte)0x18)),
            ["SuccessGlyphBrush"] = AccentEngine.Glyph(Success.Base, Success.Strong),

            // Destructive controls are neutral until hovered, so none of these is ever the
            // resting state of a delete button.
            ["DestructiveHoverBrush"] = Hex(WithAlpha(danger, isLight ? (byte)0x22 : (byte)0x33)),
            ["DestructivePressedBrush"] = Hex(WithAlpha(danger, isLight ? (byte)0x33 : (byte)0x4D)),
            ["DestructiveBorderBrush"] = isLight ? "#FFF0C2C8" : "#FF5A3038",
            ["ErrorSurfaceBrush"] = isLight ? "#FFFDF2F3" : "#FF241A1E",
            ["ErrorBorderBrush"] = isLight ? "#FFF0C2C8" : "#FF5A3038"
        };
    }

    // ==================================================================== colour arithmetic

    public static Color ToColor(string value) =>
        (Color)ColorConverter.ConvertFromString(value)!;

    private static string Hex(Color colour) => string.Format(
        CultureInfo.InvariantCulture, "#{0:X2}{1:X2}{2:X2}{3:X2}",
        colour.A, colour.R, colour.G, colour.B);

    /// <summary>Linear blend. <paramref name="amount"/> of 1 returns <paramref name="b"/>.</summary>
    private static Color Mix(Color a, Color b, double amount)
    {
        byte Channel(byte x, byte y) => (byte)Math.Round(x + ((y - x) * amount), MidpointRounding.AwayFromZero);

        return Color.FromArgb(
            Channel(a.A, b.A), Channel(a.R, b.R), Channel(a.G, b.G), Channel(a.B, b.B));
    }

    private static Color WithAlpha(Color colour, byte alpha) =>
        Color.FromArgb(alpha, colour.R, colour.G, colour.B);

