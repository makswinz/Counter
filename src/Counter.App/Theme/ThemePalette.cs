/// <summary>
/// The five stops of one illuminated gradient, in the order they are painted.
///
/// Five rather than three because three cannot describe light. A three-stop ramp reads as a
/// blend between two colours with something in the middle; five gives the lit edge somewhere to
/// go before the material's own colour arrives, and gives the shadowed half room to deepen
/// without the middle looking washed out. The offsets are fixed for every gradient in the
/// application - 0, 18, 48, 76 and 100 percent - so two gradients side by side are lit the same
/// way even when they are different colours.
/// </summary>
/// <param name="Highlight">0 percent. Where the light meets the material, at the upper left.</param>
/// <param name="Light">18 percent. Still lit, but the colour is readable in it.</param>
/// <param name="Base">48 percent. The true colour of the family.</param>
/// <param name="Strong">76 percent. Turning away from the light.</param>
/// <param name="Deep">100 percent. The shadowed edge, at the lower right.</param>
public readonly record struct GradientRamp(
    string Highlight, string Light, string Base, string Strong, string Deep)
{
    /// <summary>Builds the ramp for one accent, straight off the engine.</summary>
    public static GradientRamp From(AccentRamp ramp) =>
        new(ramp.Highlight, ramp.Light, ramp.Base, ramp.Strong, ramp.Deep);

    /// <summary>Builds the ramp for a semantic state from its one defining colour.</summary>
    public static GradientRamp FromBase(string colour) => From(AccentEngine.Derive(colour));

    /// <summary>The five stops in painting order, so a brush builder does not repeat itself.</summary>
    public IReadOnlyList<string> Stops => new[] { Highlight, Light, Base, Strong, Deep };
}

/// <summary>
/// Every colour in the application, assembled from three independent inputs.
///
/// 1. <b>Neutral</b> - the glass, the ink and the structural contours that make up almost all of
///    the interface. Two hand-tuned sets, one per theme, carrying exactly the same keys. A key
///    present in one and missing in the other is a control that goes black in light mode or
///    invisible in dark mode, which is the single most common way a second theme rots, so a test
///    asserts the sets are identical and the failure lands on a build rather than on somebody's
///    screen.
///
/// 2. <b>Accent</b> - everything that follows the colour the user picked. Not listed: generated,
///    stop by stop, by <see cref="AccentEngine"/> from that one colour. There is no orange branch
///    and no blue branch. Choosing Orange cannot leave a blue focus ring behind in some corner
///    nobody looked at, because nothing anywhere names a colour.
///
/// 3. <b>Semantic</b> - paused, warning, error and completed. Fixed families that do not follow
///    the accent, because a paused timer that turns pink when the accent is pink has stopped
///    carrying information. They are generated by the same engine from their own base colours,
///    so a red ramp is lit exactly the way an accent ramp is; only the hue is fixed.
///
/// The solid map is what <see cref="ThemeService"/> pushes into the resource dictionary. The
/// gradient map is separate because gradients are built as brushes with stops rather than parsed
/// from a string, and because the rule about where a gradient may appear is worth being able to
/// state in one place: an active control, a status indicator, and nothing else.
/// </summary>
public static class ThemePalette
